import { chromium } from 'playwright';
const W = 1280, H = 720;
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: W, height: H } });
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.text()); });
const go = async (path) => { await p.goto('http://localhost:4321/' + path, { waitUntil: 'networkidle' }); await p.waitForTimeout(1200); };
const to = async (y) => { await p.evaluate(y => window.innoLenis.scrollTo(y, { immediate: true, force: true }), y); await p.waitForTimeout(2200); };
await go('en/');
const sx = await p.evaluate(() => { const s = document.querySelector('[data-sectors]'); return s.getBoundingClientRect().top + scrollY; });
await to(sx + 5); await p.screenshot({ path: '.shots/3d-home-sx0.png' });
await to(sx + H * 0.32 * 4 + 5); await p.screenshot({ path: '.shots/3d-home-sx4.png' });
await go('en/services/warehouse-management.html');
const f = await p.evaluate(() => document.querySelector('.feat-sec').getBoundingClientRect().top + scrollY);
await to(f); await p.screenshot({ path: '.shots/3d-svc.png' });
await go('sectors/pharma.html'); await p.waitForTimeout(1500); await p.screenshot({ path: '.shots/3d-sector-ar.png' });
await go('en/about.html'); await p.waitForTimeout(1500); await p.screenshot({ path: '.shots/3d-about.png' });
const is3d = await p.evaluate(() => document.querySelector('.m3d')?.className);
console.log(JSON.stringify({ errs, is3d }));
await b.close();
