import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.goto('http://localhost:4321/index.html', { waitUntil: 'networkidle' });
await p.waitForTimeout(1500);
const state = () => p.evaluate(() => [...document.querySelectorAll('[data-mega-trigger]')].map(b => b.getAttribute('aria-expanded') === 'true' ? b.textContent.trim().slice(0, 8) : null).filter(Boolean).join(',') || 'closed');
const center = async (sel) => { const r = await p.locator(sel).first().boundingBox(); return [r.x + r.width / 2, r.y + r.height / 2]; };
const log = [];
let [x, y] = await center('[aria-controls="mega-solutions"]');
await p.mouse.move(x, y, { steps: 5 }); await p.waitForTimeout(400); log.push('hover Solutions → ' + await state());
[x, y] = await center('.nav-list a[href$="pricing.html"]');
await p.mouse.move(x, y, { steps: 8 }); await p.waitForTimeout(500); log.push('move to Pricing link → ' + await state());
[x, y] = await center('[aria-controls="mega-sectors"]');
await p.mouse.move(x, y, { steps: 5 }); await p.waitForTimeout(400); log.push('hover Sectors → ' + await state());
await p.mouse.move(x, 700, { steps: 10 }); await p.waitForTimeout(500); log.push('move down to page (scrim) → ' + await state());
[x, y] = await center('[aria-controls="mega-solutions"]');
await p.mouse.move(x, y, { steps: 5 }); await p.waitForTimeout(400);
await p.mouse.move(x, y + 140, { steps: 12 }); await p.waitForTimeout(500); log.push('trigger → into panel → ' + await state());
await p.mouse.move(700, 40, { steps: 6 }); await p.waitForTimeout(500); log.push('move to header bar gap → ' + await state());
console.log(log.join('\n'));
await b.close();
